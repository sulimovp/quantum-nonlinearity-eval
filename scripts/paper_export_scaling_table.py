#!/usr/bin/env python3
"""Export side-by-side NLPS ranks at two (n,L) points and Kendall tau stability."""

from __future__ import annotations

import argparse
import json
import math
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
from scipy import stats

METHODS: tuple[tuple[str, str], ...] = (
    ("Data reuploading", "data_reuploading"),
    ("Ancilla tracing", "ancilla_tracing"),
    ("Ancilla reuploading", "ancilla_reuploading"),
    ("Strongly entangling", "strongly_entangling"),
    ("Quantum CNN", "qcnn"),
    ("Quantum reservoir", "quantum_reservoir"),
)


def _load_json(path: Path):
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def _discover_seed_dirs(sweep_root: Path) -> list[Path]:
    if not sweep_root.is_dir():
        return []
    dirs = sorted(p for p in sweep_root.iterdir() if p.is_dir() and p.name.startswith("seed_"))
    return [p for p in dirs if (p / "nlps_final_scores.json").is_file()]


def _mean_nlps(sweep_root: Path) -> dict[str, float]:
    seed_dirs = _discover_seed_dirs(sweep_root)
    acc: dict[str, list[float]] = {k: [] for _, k in METHODS}
    for d in seed_dirs:
        data = _load_json(d / "nlps_final_scores.json")
        for _, key in METHODS:
            v = data.get(key, {}).get("NLPS")
            if isinstance(v, (int, float)) and math.isfinite(float(v)):
                acc[key].append(float(v))
    return {k: float(np.mean(vs)) if vs else math.nan for k, vs in acc.items()}


def _rank(scores: dict[str, float]) -> list[str]:
    return sorted(scores, key=lambda m: scores[m], reverse=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--n1", type=int, default=3)
    ap.add_argument("--l1", type=int, default=3)
    ap.add_argument("--n2", type=int, default=4)
    ap.add_argument("--l2", type=int, default=4)
    args = ap.parse_args()

    root = Path(__file__).resolve().parent.parent
    s1 = root / "results" / "sweeps" / f"n{args.n1}_L{args.l1}"
    s2 = root / "results" / "sweeps" / f"n{args.n2}_L{args.l2}"
    if not _discover_seed_dirs(s1):
        raise SystemExit(f"Missing sweep data: {s1}")
    if not _discover_seed_dirs(s2):
        raise SystemExit(f"Missing sweep data: {s2}")

    scores1 = _mean_nlps(s1)
    scores2 = _mean_nlps(s2)
    rank1 = _rank(scores1)
    rank2 = _rank(scores2)
    pos1 = {m: i for i, m in enumerate(rank1)}
    pos2 = [pos1[m] for m in rank2]
    tau, _ = stats.kendalltau(range(len(rank1)), pos2)
    tau = float(tau) if tau is not None and math.isfinite(tau) else math.nan

    lines = [
        "% Auto-generated by scripts/paper_export_scaling_table.py",
        f"% Kendall tau between (n,L)=({args.n1},{args.l1}) and ({args.n2},{args.l2}) mean NLPS ranks: {tau:.3f}",
        "\\begin{table}[t]",
        f"  \\caption{{Mean \\nlps\\ and ranks at $(n,L)=({args.n1},{args.l1})$ vs $({args.n2},{args.l2})$ (quantum ans\\\"atze only). Kendall $\\tau={tau:.2f}$ between the two rank orderings.}}",
        "  \\label{tab:scaling-n4-l4}",
        "  \\centering",
        "  \\small",
        "  \\begin{tabular}{lrrr}",
        "    \\toprule",
        f"    Method & NLPS $({args.n1},{args.l1})$ & NLPS $({args.n2},{args.l2})$ & $\\Delta$ rank \\\\",
        "    \\midrule",
    ]
    for label, key in METHODS:
        v1 = scores1.get(key, math.nan)
        v2 = scores2.get(key, math.nan)
        dr = pos1[key] - rank2.index(key)
        s1f = f"{v1:.3f}" if math.isfinite(v1) else "---"
        s2f = f"{v2:.3f}" if math.isfinite(v2) else "---"
        drs = f"{dr:+d}" if math.isfinite(v1) and math.isfinite(v2) else "---"
        lines.append(f"    {label} & {s1f} & {s2f} & {drs} \\\\")
    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}", ""]

    gen = root / "neurips2026" / "generated" / "scaling_n4_l4_table.tex"
    gen.write_text("\n".join(lines), encoding="utf-8")

    meta = {
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "point1": {"n": args.n1, "L": args.l1, "scores": scores1, "ranking": rank1},
        "point2": {"n": args.n2, "L": args.l2, "scores": scores2, "ranking": rank2},
        "kendall_tau": tau,
    }
    out = root / "results" / "scaling_comparison" / "summary.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2)
    print(f"Wrote {gen} (Kendall tau={tau:.3f})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
