#!/usr/bin/env python3
"""Correlate protocol component scores with downstream task performance.

Reads per-seed artifacts under ``results/sweeps/n{n}_L{L}/seed_*`` and writes:

- ``results/downstream_correlation/summary.json``
- ``neurips2026/generated/correlation_table.tex``
- ``figures/protocol_downstream_corr.pdf`` (heatmap)
"""

from __future__ import annotations

import argparse
import json
import math
from datetime import datetime, timezone
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from scipy import stats

METHODS: tuple[str, ...] = (
    "strongly_entangling",
    "data_reuploading",
    "ancilla_tracing",
    "ancilla_reuploading",
    "qcnn",
    "quantum_reservoir",
)

PROTOCOL_COLS: tuple[tuple[str, str], ...] = (
    ("NLC", "NLC"),
    ("1-BPPI", "1-BPPI"),
    ("TER", "TER"),
    ("NSS", "NSS"),
    ("NLPS", "NLPS"),
)

DOWNSTREAM_COLS: tuple[tuple[str, str], ...] = (
    ("lorenz_r2", "Lorenz $R^2$"),
    ("circles", "Circles"),
    ("moons", "Moons"),
    ("iris_1v2", "Iris (1v2)"),
    ("x_sin_x", "x sin x"),
    ("mackey_glass", "Mackey--Glass"),
)


def _load_json(path: Path):
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def _discover_seed_dirs(sweep_root: Path) -> list[Path]:
    if not sweep_root.is_dir():
        return []
    dirs = sorted(p for p in sweep_root.iterdir() if p.is_dir() and p.name.startswith("seed_"))
    return [p for p in dirs if (p / "nlps_final_scores.json").is_file()]


def _mean_over_seeds(seed_dirs: list[Path], loader) -> dict[str, float]:
  out: dict[str, list[float]] = {m: [] for m in METHODS}
  for d in seed_dirs:
      vals = loader(d)
      for m, v in vals.items():
          if v is not None and math.isfinite(v):
              out[m].append(v)
  return {m: float(np.mean(xs)) if xs else math.nan for m, xs in out.items()}


def _protocol_vectors(seed_dirs: list[Path]) -> dict[str, dict[str, float]]:
    acc: dict[str, dict[str, list[float]]] = {m: {k: [] for k, _ in PROTOCOL_COLS} for m in METHODS}
    for d in seed_dirs:
        data = _load_json(d / "nlps_final_scores.json")
        for m in METHODS:
            block = data.get(m, {})
            for key, _ in PROTOCOL_COLS:
                v = block.get(key)
                if isinstance(v, (int, float)) and math.isfinite(float(v)):
                    acc[m][key].append(float(v))
    return {
        m: {k: float(np.mean(vs)) if vs else math.nan for k, vs in acc[m].items()}
        for m in METHODS
    }


def _downstream_vectors(seed_dirs: list[Path]) -> dict[str, dict[str, float]]:
    acc: dict[str, dict[str, list[float]]] = {m: {k: [] for k, _ in DOWNSTREAM_COLS} for m in METHODS}
    for d in seed_dirs:
        lorenz = _load_json(d / "lorenz_results.json")
        real = _load_json(d / "real_data_scores.json")
        for m in METHODS:
            lb = lorenz.get(m, {})
            r2 = lb.get("r2_test") if isinstance(lb, dict) else None
            if isinstance(r2, (int, float)) and math.isfinite(float(r2)):
                acc[m]["lorenz_r2"].append(float(r2))
            for ds_key, _ in DOWNSTREAM_COLS:
                if ds_key == "lorenz_r2":
                    continue
                ds_block = real.get(ds_key, {})
                mb = ds_block.get(m, {}) if isinstance(ds_block, dict) else {}
                score = mb.get("score") if isinstance(mb, dict) else None
                if isinstance(score, (int, float)) and math.isfinite(float(score)):
                    acc[m][ds_key].append(float(score))
    return {
        m: {k: float(np.mean(vs)) if vs else math.nan for k, vs in acc[m].items()}
        for m in METHODS
    }


def _corr_matrix(
    protocol: dict[str, dict[str, float]],
    downstream: dict[str, dict[str, float]],
    method: str = "spearman",
) -> tuple[np.ndarray, list[str], list[str]]:
    p_keys = [k for k, _ in PROTOCOL_COLS]
    d_keys = [k for k, _ in DOWNSTREAM_COLS]
    p_mat = np.array([[protocol[m][k] for k in p_keys] for m in METHODS], dtype=float)
    d_mat = np.array([[downstream[m][k] for k in d_keys] for m in METHODS], dtype=float)
    corr = np.full((len(p_keys), len(d_keys)), math.nan)
    for i, _ in enumerate(p_keys):
        for j, _ in enumerate(d_keys):
            x = p_mat[:, i]
            y = d_mat[:, j]
            mask = np.isfinite(x) & np.isfinite(y)
            if mask.sum() < 3:
                continue
            if method == "kendall":
                corr[i, j], _ = stats.kendalltau(x[mask], y[mask])
            else:
                corr[i, j], _ = stats.spearmanr(x[mask], y[mask])
    return corr, [lbl for _, lbl in PROTOCOL_COLS], [lbl for _, lbl in DOWNSTREAM_COLS]


def _write_latex(corr: np.ndarray, row_labels: list[str], col_labels: list[str], out: Path) -> None:
    lines = [
        "% Auto-generated by scripts/downstream_protocol_correlation.py",
        "\\begin{table}[t]",
        "  \\caption{Spearman $\\rho$ between protocol scalars (rows; one value per method, averaged over seeds) and downstream task scores (columns). $n=6$ quantum ans\\\"atze at $(n,L)=(3,3)$.}",
        "  \\label{tab:downstream-correlation}",
        "  \\centering",
        "  \\footnotesize",
        "  \\setlength{\\tabcolsep}{4pt}",
        "  \\begin{tabular}{l" + "r" * len(col_labels) + "}",
        "    \\toprule",
        "    & " + " & ".join(col_labels) + " \\\\",
        "    \\midrule",
    ]
    for i, rl in enumerate(row_labels):
        cells = []
        for j in range(len(col_labels)):
            v = corr[i, j]
            cells.append("---" if not math.isfinite(v) else f"{v:+.2f}")
        lines.append(f"    {rl} & " + " & ".join(cells) + " \\\\")
    lines += [
        "    \\bottomrule",
        "  \\end{tabular}",
        "\\end{table}",
        "",
    ]
    out.write_text("\n".join(lines), encoding="utf-8")


def _plot_heatmap(corr: np.ndarray, row_labels: list[str], col_labels: list[str], out: Path) -> None:
    fig, ax = plt.subplots(figsize=(7.5, 3.8))
    im = ax.imshow(corr, vmin=-1, vmax=1, cmap="RdBu_r", aspect="auto")
    ax.set_xticks(range(len(col_labels)))
    ax.set_xticklabels(col_labels, rotation=35, ha="right", fontsize=8)
    ax.set_yticks(range(len(row_labels)))
    ax.set_yticklabels(row_labels, fontsize=9)
    for i in range(corr.shape[0]):
        for j in range(corr.shape[1]):
            v = corr[i, j]
            if math.isfinite(v):
                ax.text(j, i, f"{v:+.2f}", ha="center", va="center", fontsize=7)
    fig.colorbar(im, ax=ax, fraction=0.03, pad=0.02, label="Spearman $\\rho$")
    ax.set_title("Protocol scores vs downstream tasks (method-level, $K$ seeds)")
    fig.tight_layout()
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--n", type=int, default=3)
    ap.add_argument("--l", type=int, default=3)
    args = ap.parse_args()

    root = Path(__file__).resolve().parent.parent
    sweep_root = root / "results" / "sweeps" / f"n{args.n}_L{args.l}"
    seed_dirs = _discover_seed_dirs(sweep_root)
    if not seed_dirs:
        raise SystemExit(f"No seed dirs under {sweep_root}")

    protocol = _protocol_vectors(seed_dirs)
    downstream = _downstream_vectors(seed_dirs)
    spearman, row_labels, col_labels = _corr_matrix(protocol, downstream, "spearman")
    kendall, _, _ = _corr_matrix(protocol, downstream, "kendall")

    out_dir = root / "results" / "downstream_correlation"
    out_dir.mkdir(parents=True, exist_ok=True)
    summary = {
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "sweep_root": str(sweep_root.relative_to(root)),
        "n_seeds": len(seed_dirs),
        "methods": list(METHODS),
        "protocol_by_method": protocol,
        "downstream_by_method": downstream,
        "spearman": spearman.tolist(),
        "kendall": kendall.tolist(),
        "row_labels": row_labels,
        "col_labels": col_labels,
    }
    _write_json = out_dir / "summary.json"
    with _write_json.open("w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    gen = root / "neurips2026" / "generated" / "correlation_table.tex"
    _write_latex(spearman, row_labels, col_labels, gen)
    _plot_heatmap(spearman, row_labels, col_labels, root / "figures" / "protocol_downstream_corr.pdf")
    print(f"Wrote {out_dir / 'summary.json'}, {gen}, figures/protocol_downstream_corr.pdf")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
